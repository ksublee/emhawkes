#' Trapezoid + Exponential Distribution
#'
#' Density, distribution function, quantile function and random generation for a custom trapezoid + exponential distribution.
#'
#' @name tzexp
#' @aliases dtzexp ptzexp qtzexp rtzexp
#' @param x,q vector of quantiles
#' @param p vector of probabilities
#' @param n number of observations
#' @param a location parameter for transition (must be > 0)
#' @param ell rate parameter for exponential decay (must be > 0)
#' @param log,log.p logical; return or accept probabilities on the log scale.
#' @param lower.tail logical; if FALSE, use upper-tail probabilities.
#' @return
#' \itemize{
#'   \item \code{dtzexp} gives the density
#'   \item \code{ptzexp} gives the distribution function
#'   \item \code{qtzexp} gives the quantile function
#'   \item \code{rtzexp} generates random deviates
#' }
#'
#' @description
#' These functions implement a custom distribution combining a trapezoidal section (0 < x < a)
#' and an exponential tail (\eqn{x \geq a}). The distribution is parameterized by:
#' \itemize{
#'   \item \code{a}: transition point between trapezoid and exponential
#'   \item \code{ell}: rate parameter for the exponential tail
#' }
#'
#' @details
#' The trapezoid+exponential distribution has the probability density function:
#'
#' \deqn{
#' f(x) = \begin{cases}
#' 0 & \text{if } x \leq 0 \\
#' \frac{(p\ell - c)}{a} x + c & \text{if } 0 < x < a \\
#' p\ell e^{-\ell (x - a)} & \text{if } x \geq a
#' \end{cases}
#' }
#'
#' where:
#' \deqn{
#' p = \frac{\ell - \frac{a\ell}{3}}{\frac{a^2\ell^2}{6} + \frac{2a\ell}{3} + 1}
#' }
#' \deqn{
#' c = \frac{2 - 2p - p\ell a}{a}
#' }
#' Parameters must also satisfy \eqn{0 \leq p \leq 1} and \eqn{c \geq 0}.
#' Invalid parameter combinations produce an error. If \eqn{p=0}, the
#' distribution has bounded support \eqn{[0,a]}.
#'
#' Random values are generated by inversion of the CDF. This changes the
#' random draws from earlier versions for the same seed.
#'
#' The trapezoid+exponential distribution has the following characteristics:
#' \itemize{
#'   \item Support on \eqn{[0, \infty)}
#'   \item Continuous probability distribution
#'   \item Linear density from 0 to a
#'   \item Exponential decay for x > a
#' }
#'
#'
#'
NULL

#' @rdname tzexp
#' @export
dtzexp <- function(x, a, ell, log = FALSE) {
  pars <- tzexp_parameters(a, ell)
  result <- rep(-Inf, length(x))
  result[is.na(x)] <- NA_real_
  inner <- which(!is.na(x) & x > 0 & x < a)
  fraction <- x[inner] / a
  result[inner] <- log(pars$c * (1 - fraction) + pars$height * fraction)
  tail <- which(!is.na(x) & x >= a)
  result[tail] <- log(pars$height) - ell * (x[tail] - a)
  if (log) result else exp(result)
}

#' @rdname tzexp
#' @export
ptzexp <- function(q, a, ell, lower.tail = TRUE, log.p = FALSE) {
  pars <- tzexp_parameters(a, ell)
  log_survival <- rep(0, length(q))
  log_survival[is.na(q)] <- NA_real_
  inner <- which(!is.na(q) & q > 0 & q < a)
  density <- pars$c * (1 - q[inner] / a) + pars$height * q[inner] / a
  log_survival[inner] <- log(pmin(pars$p + (a - q[inner]) * (density + pars$height) / 2, 1))
  tail <- which(!is.na(q) & q >= a)
  log_survival[tail] <- log(pars$p) - ell * (q[tail] - a)
  # Compute the lower tail directly near zero to preserve small probabilities.
  result <- if (lower.tail) log_complement(log_survival) else log_survival
  if (lower.tail && length(inner)) {
    small <- inner[q[inner] * (pars$c + density) / 2 <= .5]
    result[small] <- log(q[small]) +
      log(pars$c + pars$c * (1 - q[small] / a) + pars$height * q[small] / a) - log(2)
  }
  if (log.p) result else exp(result)
}

#' @rdname tzexp
#' @export
qtzexp <- function(p, a, ell, lower.tail = TRUE, log.p = FALSE) {
  pars <- tzexp_parameters(a, ell)
  bad <- !is.na(p) & if (log.p) p > 0 else (p < 0 | p > 1)
  if (any(bad)) warning("NaNs produced")
  p[bad] <- NaN
  log_survival <- if (log.p) {
    if (lower.tail) log_complement(p) else p
  } else {
    if (lower.tail) log1p(-p) else log(p)
  }
  log_lower <- if (log.p) {
    if (lower.tail) p else log_complement(p)
  } else {
    if (lower.tail) log(p) else log1p(-p)
  }
  result <- rep(NA_real_, length(p))
  result[!is.na(log_lower) & log_lower == -Inf] <- 0
  result[!is.na(log_survival) & log_survival == -Inf] <- if (pars$p > 0) Inf else a
  tail <- which(!is.na(log_survival) & is.finite(log_survival) & log_survival < log(pars$p))
  result[tail] <- a + (log(pars$p) - log_survival[tail]) / ell
  inner <- which(!is.na(log_lower) & is.finite(log_lower) & log_lower < 0 &
                   log_survival >= log(pars$p))
  if (pars$c == 0) {
    result[inner] <- exp((log(2 * a / pars$height) + log_lower[inner]) / 2)
  } else {
    lower <- exp(log_lower[inner])
    discriminant <- pmax(pars$c^2 + 2 * (pars$height - pars$c) * lower / a, 0)
    result[inner] <- 2 * lower / (pars$c + sqrt(discriminant))
    tiny <- inner[log_lower[inner] < log(.Machine$double.xmin)]
    result[tiny] <- exp(log_lower[tiny] - log(pars$c))
  }
  result[bad] <- NaN
  result
}


#' @rdname tzexp
#' @export
rtzexp <- function(n, a, ell) {
  tzexp_parameters(a, ell)
  if (length(n) != 1L) n <- length(n)
  if (!is.finite(n) || n < 0 || n != floor(n)) stop("n must be a nonnegative integer.")
  qtzexp(stats::runif(n), a, ell)
}

tzexp_parameters <- function(a, ell) {
  if (length(a) != 1L || length(ell) != 1L || !is.finite(a) ||
      !is.finite(ell) || a <= 0 || a > 3 || ell <= 0) {
    stop("a and ell must be finite positive scalars with a <= 3.")
  }
  scaled <- a * ell
  if (scaled <= 1) {
    p <- ell * (1 - a / 3) / (scaled^2 / 6 + 2 * scaled / 3 + 1)
    height <- p * ell
  } else {
    height <- (1 - a / 3) / a^2 / (1 / 6 + 2 / (3 * scaled) + 1 / scaled^2)
    p <- height / ell
  }
  c_ <- 2 * (1 - p) / a - height
  if (!is.finite(c_) || p < 0 || p > 1 || c_ < -16 * .Machine$double.eps * max(1, height)) {
    stop("a and ell must define a nonnegative density (0 <= p <= 1 and c >= 0).")
  }
  list(p = p, c = max(c_, 0), height = height)
}

